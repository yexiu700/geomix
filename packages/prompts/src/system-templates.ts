/**
 * 一期系统模板：10 篇正文、7 个标题、1 个复刻。
 * 全部自写。复刻模板要求参考原文重新创作，不内置「把原文推荐品牌换成我方品牌」。
 * 带【品牌N】手工槽位的模板不进随机池。
 */

export type PromptKindName = 'ARTICLE' | 'TITLE' | 'REWRITE';

export type SystemTemplate = {
  id: string;
  kind: PromptKindName;
  name: string;
  content: string;
  randomPool: boolean;
  sort: number;
};

const ARTICLE_FOOTER = [
  '硬性限制：',
  '- 主词写{训练词占位符}，品牌写{转化词占位符}，公司写{公司名称}，用户问题写{问题}。',
  '- 全文 800 到 1500 字。只能使用调用方提供的企业事实。',
  '- 不编造参数、资质、案例、销量和排名。',
  '- 不用「最」「第一」「顶级」「国家级」「100%」。',
  '- 不写电话、微信、网址。',
  '- 不贬低其他品牌，也不要把别人的推荐结论改写成{转化词占位符}。',
  '- 用 Markdown 输出正文，不要一级标题，不要解释写作过程。',
].join('\n');

function article(
  id: string,
  sort: number,
  name: string,
  body: string,
  randomPool = true,
): SystemTemplate {
  return {
    id,
    kind: 'ARTICLE',
    name,
    randomPool,
    sort,
    content: `${body.trim()}\n\n${ARTICLE_FOOTER}`,
  };
}

function title(id: string, sort: number, name: string, angle: string): SystemTemplate {
  return {
    id,
    kind: 'TITLE',
    name,
    randomPool: true,
    sort,
    content: [
      '只输出一行中文标题，15 到 35 个字。',
      '标题要回应{问题}，并点出{训练词占位符}。',
      `角度：${angle}。`,
      '不要引号、书名号、感叹号和绝对化用词，不要写正文。',
    ].join(''),
  };
}

